"""Build a Babarify Frame release (M10): program folder, installer, source archive, checksums.

Steps: curate libVLC (tools/vlc_plugins.py) → PyInstaller (packaging/babarify.spec) → add the
engine, LICENSE, notices, privacy notice and release notes → source archive (git archive of
HEAD) → Inno Setup installer → SHA256SUMS.txt and a manifest of every shipped file.
Output: release/<version>/.  Requires a clean git tree unless --allow-dirty.
Usage:  python tools/build_release.py [--allow-dirty] [--version X.Y.Z]
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
import notices
import vlc_plugins
from babarify_frame import __version__
from babarify_frame.core.models import MEDIA_EXTENSIONS

ROOT = Path(__file__).resolve().parents[1]
BUILD = ROOT / "build"
ISCC = Path(os.environ.get("LOCALAPPDATA", "")) / "Programs" / "Inno Setup 6" / "ISCC.exe"
PY = sys.executable


def run(*cmd: str, capture: bool = False, cwd: Path = ROOT) -> str:
    print(">", " ".join(cmd))
    done = subprocess.run(cmd, check=True, text=True, capture_output=capture, cwd=cwd)
    return done.stdout or ""


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        while chunk := stream.read(1 << 20):
            digest.update(chunk)
    return digest.hexdigest()


def version_info(version: str) -> str:
    nums = tuple(([int(p) for p in version.split(".")] + [0, 0, 0])[:4])
    fixed = f"filevers={nums}, prodvers={nums}, mask=0x3f, flags=0x0, OS=0x40004"
    return f"""VSVersionInfo(
  ffi=FixedFileInfo({fixed}, fileType=0x1, subtype=0x0, date=(0, 0)),
  kids=[
    StringFileInfo([StringTable('040904B0', [
      StringStruct('CompanyName', 'Tanveer Baber'),
      StringStruct('FileDescription', 'Babarify Frame media player'),
      StringStruct('FileVersion', '{version}'),
      StringStruct('LegalCopyright', 'Copyright (C) 2026 Tanveer Baber. GNU GPL v3 or later.'),
      StringStruct('ProductName', 'Babarify Frame'),
      StringStruct('ProductVersion', '{version}')])]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def assoc_iss() -> str:
    """Inno Setup registry lines for "Open with" (one set per media extension)."""
    lines = ["; generated by tools/build_release.py from core.models.MEDIA_EXTENSIONS"]
    for ext in sorted(MEDIA_EXTENSIONS):
        for subkey, name, data in (
            (f"Software\\Classes\\{ext}\\OpenWithProgids", "{#ProgId}", ""),
            ("Software\\Classes\\Applications\\{#AppExe}\\SupportedTypes", ext, ""),
            ("Software\\Babarify\\Frame\\Capabilities\\FileAssociations", ext, "{#ProgId}"),
        ):
            flags = "; Flags: uninsdeletevalue" if "OpenWithProgids" in subkey else ""
            lines.append(
                f'Root: HKCU; Subkey: "{subkey}"; ValueType: string; ValueName: "{name}"; '
                f'ValueData: "{data}"{flags}; Tasks: openwith'
            )
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--allow-dirty", action="store_true")
    parser.add_argument("--version", default=__version__)
    args = parser.parse_args()
    version = args.version
    dirty = run("git", "status", "--porcelain", capture=True).strip()
    if dirty and not args.allow_dirty:
        print("the working tree has changes; commit first or pass --allow-dirty", file=sys.stderr)
        return 1
    commit = run("git", "rev-parse", "HEAD", capture=True).strip()
    out = ROOT / "release" / version
    shutil.rmtree(out, ignore_errors=True)
    out.mkdir(parents=True)
    BUILD.mkdir(exist_ok=True)

    engine = BUILD / "engines" / "vlc"
    vlc_plugins.curate(vlc_plugins.DEFAULT_VLC, engine)
    (BUILD / "version_info.txt").write_text(version_info(version), encoding="utf-8")
    (BUILD / "assoc.iss").write_text(assoc_iss(), encoding="utf-8")
    run(PY, "-m", "PyInstaller", "--noconfirm", "--clean", "--log-level", "WARN",
        "--distpath", str(BUILD / "dist"), "--workpath", str(BUILD / "pyinstaller"),
        str(ROOT / "packaging" / "babarify.spec"))  # fmt: skip
    dist = BUILD / "dist" / "Babarify Frame"
    shutil.copytree(BUILD / "dist" / "ai", dist / "ai")  # the optional local AI component
    shutil.copytree(engine, dist / "engines" / "vlc", ignore=shutil.ignore_patterns("plugins.json"))
    shutil.copy2(ROOT / "LICENSE", dist / "LICENSE.txt")
    shutil.copy2(ROOT / "docs" / "PRIVACY.md", dist / "PRIVACY.txt")
    notes = ROOT / "docs" / "release-notes" / f"{version}.md"
    if notes.is_file():
        shutil.copy2(notes, dist / "RELEASE-NOTES.txt")
    elif dirty:  # a test build (e.g. the upgrade check): no published notes
        (dist / "RELEASE-NOTES.txt").write_text(f"Babarify Frame {version} (test build)\n", encoding="utf-8")
    else:
        print(f"missing {notes}", file=sys.stderr)
        return 1
    notices.write(dist, engine, version)

    source = out / f"BabarifyFrame-{version}-source.zip"
    run("git", "archive", "--format=zip", f"--prefix=babarify-frame-{version}/", "-o", str(source), commit)
    run(str(ISCC), "/Q", f"/DAppVersion={version}", f"/DDistDir={dist}", f"/DOutputDir={out}",
        str(ROOT / "packaging" / "installer.iss"))  # fmt: skip

    files = sorted(p for p in dist.rglob("*") if p.is_file())
    entries = [
        {"path": str(p.relative_to(dist)), "size": p.stat().st_size, "sha256": sha256(p)} for p in files
    ]
    manifest = {"version": version, "commit": commit, "dirty": bool(dirty), "files": entries}
    manifest_path = out / f"BabarifyFrame-{version}-manifest.json"
    manifest_path.write_text(json.dumps(manifest, indent=1), encoding="utf-8")
    artifacts = sorted(p for p in out.iterdir() if p.is_file() and p.name != "SHA256SUMS.txt")
    sums = "".join(f"{sha256(p)}  {p.name}\n" for p in artifacts)
    (out / "SHA256SUMS.txt").write_text(sums, encoding="utf-8")
    size = sum(p.stat().st_size for p in files)
    state = " (dirty)" if dirty else ""
    print(f"program folder: {len(files)} files, {size / 1e6:.0f} MB; commit {commit[:10]}{state}")
    for p in artifacts:
        print(f"{p.name}: {p.stat().st_size / 1e6:.1f} MB")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
